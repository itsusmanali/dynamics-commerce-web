"use client";

import Image from "next/image";
import Link from "next/link";
import { useMemo, useState } from "react";
import type { CategoryNode, HeaderData, MenuItem } from "./header.data";
import type { HeaderProps } from "./header.props.autogenerated";
import type { ModuleDataActionDefinition } from "../module.types";
import { useDataAction } from "@/lib/api/data-actions/client";
import styles from "./header.module.scss";

function MenuBranch({
  item,
  depth = 0,
  onNavigate,
}: {
  item: MenuItem;
  depth?: number;
  onNavigate: () => void;
}) {
  if (!item.children?.length)
    return (
      <Link href={item.href} onClick={onNavigate}>
        {item.label}
      </Link>
    );
  return (
    <details className={styles.branch}>
      <summary>
        {item.label}
        <span aria-hidden="true">⌄</span>
      </summary>
      <ul className={depth === 0 ? styles.dropdown : styles.nested}>
        {item.children.map((child) => (
          <li key={child.id}>
            <MenuBranch
              item={child}
              depth={depth + 1}
              onNavigate={onNavigate}
            />
          </li>
        ))}
      </ul>
    </details>
  );
}

function MegaMenu({
  item,
  onNavigate,
}: {
  item: MenuItem;
  onNavigate: () => void;
}) {
  const featured =
    item.children
      ?.flatMap((group) => group.children ?? [])
      .filter((child) => child.featured && child.image) ?? [];
  const [active, setActive] = useState(featured[0]);
  return (
    <details className={`${styles.branch} ${styles.megaBranch}`}>
      <summary>
        {item.label}
        <span aria-hidden="true">⌄</span>
      </summary>
      <div className={styles.mega}>
        <div className={styles.megaColumns}>
          {item.children?.map((group) => (
            <section key={group.id}>
              <Link
                className={styles.groupTitle}
                href={group.href}
                onClick={onNavigate}
              >
                {group.label}
              </Link>
              <ul>
                {group.children?.map((child) => (
                  <li
                    key={child.id}
                    onMouseEnter={() => child.image && setActive(child)}
                    onFocus={() => child.image && setActive(child)}
                  >
                    <MenuBranch
                      item={child}
                      depth={1}
                      onNavigate={onNavigate}
                    />
                  </li>
                ))}
              </ul>
            </section>
          ))}
        </div>
        {active?.image ? (
          <Link
            href={active.href}
            className={styles.feature}
            onClick={onNavigate}
          >
            <span className={styles.featureImage}>
              <Image src={active.image} alt="" fill sizes="320px" />
            </span>
            <strong>{active.label}</strong>
            <span>{active.description}</span>
          </Link>
        ) : null}
      </div>
    </details>
  );
}

function categoryMenu(category: CategoryNode): MenuItem {
  return {
    id: `commerce-category-${category.RecordId}`,
    label: category.Name || `Category ${category.RecordId}`,
    href: `/category/${category.RecordId}`,
    audience: "retail",
    description: category.LocalizedDescription,
    children: category.children.map(categoryMenu),
  };
}

export function HeaderView({
  id,
  config,
  resources,
  data,
  action,
  categoriesAction,
  initialCategories,
}: HeaderProps & {
  data: HeaderData | null;
  action: ModuleDataActionDefinition;
  categoriesAction: ModuleDataActionDefinition;
  initialCategories: CategoryNode[] | null;
}) {
  const [mobileOpen, setMobileOpen] = useState(false);
  const mode =
    config.menuMode === "retail" || config.menuMode === "authored"
      ? config.menuMode
      : "all";
  // These return ordinary React Query states: data, isLoading, isFetching,
  // isError, error and refetch. Execution comes only from definition.json.
  const menuQuery = useDataAction<HeaderData>(action, {
    mode,
    menuSlug: config.wordpressMenuSlug || "primary",
  }, data);
  const categoriesQuery = useDataAction<CategoryNode[]>(categoriesAction, {
    presentation: "tree",
  }, initialCategories, mode !== "authored");

  const close = () => setMobileOpen(false);
  const resolvedData = action.execution === "client" ? menuQuery.data : data;
  const menuData = useMemo(() => {
    if (!resolvedData || !categoriesQuery.data?.length) return resolvedData;
    return {
      ...resolvedData,
      items: resolvedData.items.map((item) =>
        item.id !== "commerce"
          ? item
          : {
              ...item,
              children: [
                {
                  id: "commerce-api-categories",
                  label: "Categories",
                  href: "/categories",
                  audience: "retail" as const,
                  children: (categoriesQuery.data as CategoryNode[]).map(
                    categoryMenu,
                  ),
                },
                ...(item.children ?? []),
              ],
            },
      ),
    };
  }, [categoriesQuery.data, resolvedData]);
  return (
    <header
      aria-busy={menuQuery.isFetching || categoriesQuery.isFetching}
      className={`${styles.root} ${config.sticky ? styles.sticky : ""}`}
      style={{
        backgroundColor: config.backgroundColor,
        color: config.foregroundColor,
      }}
    >
      <div
        className={`site-shell ${styles.shell} ${config.variant === "centered" ? styles.centered : ""}`}
      >
        <Link href="/" className={styles.logo} onClick={close}>
          Dynamics Commerce
        </Link>
        <button
          className={styles.mobileToggle}
          type="button"
          aria-expanded={mobileOpen}
          aria-controls={`${id}-navigation`}
          aria-label={
            mobileOpen ? resources.closeMenuLabel : resources.openMenuLabel
          }
          onClick={() => setMobileOpen((value) => !value)}
        >
          <span />
          <span />
          <span />
        </button>
        <nav
          id={`${id}-navigation`}
          aria-label={resources.menuLabel}
          className={`${styles.navigation} ${mobileOpen ? styles.navigationOpen : ""}`}
        >
          {menuQuery.isLoading ? (
            <p className={styles.loading}>{resources.loadingMenuLabel}</p>
          ) : null}
          {menuQuery.isError ? (
            <p className={styles.loading}>Navigation could not be loaded.</p>
          ) : null}
          {menuData ? (
            <ul className={styles.topLevel}>
              {menuData.items.map((item) => (
                <li key={item.id}>
                  {item.children?.length && item.id === "commerce" ? (
                    <MegaMenu item={item} onNavigate={close} />
                  ) : (
                    <MenuBranch item={item} onNavigate={close} />
                  )}
                </li>
              ))}
              <li>
                <Link href="/blog" onClick={close}>
                  {resources.blogLabel}
                </Link>
              </li>
              {config.showSearch ? (
                <li>
                  <Link href="/search" onClick={close}>
                    {resources.searchLabel}
                  </Link>
                </li>
              ) : null}
            </ul>
          ) : null}
        </nav>
      </div>
    </header>
  );
}
